export function getClassicalLineInterpretations(hexagramNumber, lineNumber){
  const h=Number(hexagramNumber), l=Number(lineNumber);
  const wilhelm=W[h]?.[l]||null;
  const shchutsky=S[h]?.[l]||null;
  return {
    available:Boolean(wilhelm||shchutsky),
    verified:Boolean(wilhelm&&shchutsky),
    corpusVersion:CLASSICAL_LINES_VERSION,
    wilhelm,
    shchutsky
  };
}

export function classicalLineCorpusStats(){
  const count=source=>Object.values(source).reduce((sum,lines)=>sum+Object.keys(lines).length,0);
  return {wilhelm:count(W),shchutsky:count(S),totalPossible:384};
}
